def assert_valid_chunks(chunks: List[Chunk]) -> None:
    """Apply assertions that must hold for any well-formed parse result."""
    assert len(chunks) > 0, "parse_document must return at least one chunk"

    # Group by page
    by_page: dict[int, List[Chunk]] = defaultdict(list)
    for c in chunks:
        by_page[c.page_number].append(c)

    for page_num, page_chunks in by_page.items():
        # Sort by reading_order_index for ordered checks
        ordered = sorted(page_chunks, key=lambda c: c.reading_order_index)

        # --- 1. Valid normalised bboxes ------------------------------------
        for c in ordered:
            x0, y0, x1, y1 = c.bbox
            assert 0.0 <= x0 <= 1.0, f"page {page_num}: x0={x0} out of [0,1]"
            assert 0.0 <= y0 <= 1.0, f"page {page_num}: y0={y0} out of [0,1]"
            assert 0.0 <= x1 <= 1.0, f"page {page_num}: x1={x1} out of [0,1]"
            assert 0.0 <= y1 <= 1.0, f"page {page_num}: y1={y1} out of [0,1]"
            assert x1 > x0, f"page {page_num}: bbox has x1 <= x0"
            assert y1 > y0, f"page {page_num}: bbox has y1 <= y0"

        # --- 2. reading_order_index is monotonically increasing ------------
        indices = [c.reading_order_index for c in ordered]
        for i in range(len(indices) - 1):
            assert indices[i] < indices[i + 1], (
                f"page {page_num}: reading_order_index not strictly increasing "
                f"at positions {i} ({indices[i]}) and {i+1} ({indices[i+1]})"
            )

        # --- 3. No text chunk substantially overlaps a table chunk ---------
        text_chunks = [c for c in ordered if c.chunk_type == "text"]
        table_chunks = [c for c in ordered if c.chunk_type == "table"]
        for tc in text_chunks:
            for tbl in table_chunks:
                overlap = _bbox_overlap(tc.bbox, tbl.bbox)
                assert overlap < 0.3, (
                    f"page {page_num}: text chunk {tc.chunk_id} overlaps "
                    f"table chunk {tbl.chunk_id} by {overlap:.1%}"
                )

        # --- 4. Only valid chunk_type literals ----------------------------
        valid_types = {"text", "table", "chart_candidate"}
        for c in ordered:
            assert c.chunk_type in valid_types, (
                f"Invalid chunk_type '{c.chunk_type}' on page {page_num}"
            )


