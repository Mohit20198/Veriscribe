"""
tests/test_ingestion.py
-----------------------
Pytest tests for the Veriscribe Phase-1 ingestion pipeline.

Tests run against two synthetic PDFs generated by conftest.py:
  - pdf_a: single-column, text-only, 3 pages.
  - pdf_b: table on page 1, embedded image on page 2.

Assertions
~~~~~~~~~~
1. All returned chunks have valid normalised bboxes (all values in [0, 1]).
2. reading_order_index is strictly monotonically increasing per page.
3. No chunk_type="text" chunk substantially overlaps a chunk_type="table"
   chunk's bbox on the same page (dedup check).
4. At least one chunk is returned per PDF.
5. Only valid chunk_type literals are used.
6. Table chunks on pdf_b page 1 carry non-empty table_data.
"""

from __future__ import annotations

import pathlib
from collections import defaultdict
from typing import List

import pytest

from ingestion.models import Chunk
from ingestion.pipeline import parse_document


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _bbox_overlap(
    a: tuple[float, float, float, float],
    b: tuple[float, float, float, float],
) -> float:
    """Return the intersection / min-area ratio for two normalised bboxes."""
    ix0 = max(a[0], b[0])
    iy0 = max(a[1], b[1])
    ix1 = min(a[2], b[2])
    iy1 = min(a[3], b[3])
    if ix1 <= ix0 or iy1 <= iy0:
        return 0.0
    inter = (ix1 - ix0) * (iy1 - iy0)
    area_a = (a[2] - a[0]) * (a[3] - a[1])
    area_b = (b[2] - b[0]) * (b[3] - b[1])
    min_area = min(area_a, area_b)
    return inter / min_area if min_area > 0 else 0.0


